export function renderReportHtml(report: ResolvedReport): string {
  const body: string[] = [];
  for (const section of report.sections) {
    body.push(`<h2 id="${slugAnchor(section.heading)}">${escapeHtml(section.heading)}</h2>`);
    for (const block of section.blocks) body.push(htmlBlock(block, report));
  }

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(report.title)}</title>
<style>${reportCss(report.theme)}</style></head>
<body><main class="page">
${renderCover(report)}
<nav class="toc"><strong>Contents</strong><ol>
${report.sections.map((s) => `<li><a href="#${slugAnchor(s.heading)}">${escapeHtml(s.heading)}</a></li>`).join('\n')}
</ol></nav>
${body.join('\n')}
<p class="footer">Passages marked <em>Inferred</em> or <em>Recommendation</em> are AI-generated
interpretation, not statements of what occurred.</p>
</main></body></html>`;
}

function htmlBlock(block: ReportBlock, report: ResolvedReport): string {
  switch (block.type) {
    case 'paragraph':
      return `<p>${escapeHtml(block.text)}</p>`;
    case 'heading':
      return `<h${block.level}>${escapeHtml(block.text)}</h${block.level}>`;
    case 'bullets': {
      const tag = block.ordered ? 'ol' : 'ul';
      return `<${tag}>${block.items.map((i) => `<li>${escapeHtml(i)}</li>`).join('')}</${tag}>`;
    }
    case 'procedure':
      return `<ol>${block.items
        .map((i) => `<li><strong>${escapeHtml(i.text)}</strong>${i.detail ? `<br><span class="meta">${escapeHtml(i.detail)}</span>` : ''}</li>`)
        .join('')}</ol>`;
    case 'code':
      return `<pre><code>${escapeHtml(block.content)}</code></pre>${block.caption ? `<p class="meta">${escapeHtml(block.caption)}</p>` : ''}`;
    case 'table':
      return `<table>${block.caption ? `<caption>${escapeHtml(block.caption)}</caption>` : ''}
        <thead><tr>${block.headers.map((h) => `<th>${escapeHtml(h)}</th>`).join('')}</tr></thead>
        <tbody>${block.rows.map((r) => `<tr>${r.map((c) => `<td>${escapeHtml(String(c))}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
    case 'figure': {
      const figure = report.figures.get(block.evidenceId);
      const img = figure?.bytes
        ? `<img src="data:${figure.mimeType};base64,${figure.bytes.toString('base64')}" alt="${escapeHtml(block.caption)}">`
        : `<p class="meta">[Image unavailable: ${escapeHtml(figure?.missingReason ?? 'not found')}]</p>`;
      return `<figure>${img}<figcaption>Figure ${block.number ?? '?'} — ${escapeHtml(block.caption)}</figcaption></figure>`;
    }
    case 'callout': {
      const label = { note: 'Note', warning: 'Caution', inference: 'Inferred', recommendation: 'Recommendation' }[block.variant];
      return `<div class="callout ${block.variant}"><span class="label">${label}</span>${escapeHtml(block.text)}</div>`;
    }
    case 'diagram':
      return `<figure><pre><code>${escapeHtml(block.ascii)}</code></pre>${block.caption ? `<figcaption>${escapeHtml(block.caption)}</figcaption>` : ''}</figure>`;
    case 'reference-list':
      return `<ol>${block.items
        .map((i) => `<li>${escapeHtml(i.label)}${i.url ? ` — <a href="${escapeHtml(i.url)}">${escapeHtml(i.url)}</a>` : ''}${i.detail ? ` — ${escapeHtml(i.detail)}` : ''}</li>`)
        .join('')}</ol>`;
    default:
      return '';
  }
}

export function renderPresentationHtml(presentation: ResolvedPresentation): string {
  const slides = presentation.slides
    .map((slide) => {
      const figures = slide.figures
        .filter((f) => f.bytes)
        .map((f) => `<img src="data:${f.mimeType};base64,${f.bytes!.toString('base64')}" alt="${escapeHtml(f.caption)}">`)
        .join('');
      return `<section class="slide">
        <h2>${escapeHtml(slide.title)}</h2>
        ${slide.subtitle ? `<p class="sub">${escapeHtml(slide.subtitle)}</p>` : ''}
        <ul>${slide.bullets.map((b) => `<li>${escapeHtml(b)}</li>`).join('')}</ul>
        ${slide.body.code ? `<pre><code>${escapeHtml(slide.body.code.content)}</code></pre>` : ''}
        ${slide.body.diagram ? `<pre><code>${escapeHtml(slide.body.diagram.ascii)}</code></pre>` : ''}
        ${figures ? `<div class="figures">${figures}</div>` : ''}
        ${slide.speakerNotes ? `<aside class="notes"><strong>Speaker notes</strong><p>${escapeHtml(slide.speakerNotes)}</p></aside>` : ''}
      </section>`;
    })
    .join('\n');

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(presentation.title)}</title>
<style>${reportCss(presentation.theme)}
.slide { border:1px solid var(--line); border-radius:12px; padding:1.5rem 1.75rem; margin:1.5rem 0; }
.slide h2 { border:0; margin-top:0; }
.slide .sub { color:var(--muted); margin-top:-.35rem; }
.slide ul { font-size:1.05rem; }
.figures { display:flex; gap:1rem; flex-wrap:wrap; }
.figures img { max-width:min(100%, 22rem); border:1px solid var(--line); border-radius:8px; }
.notes { background:var(--note); border-radius:8px; padding:.85rem 1rem; margin-top:1rem; font-size:.9rem; }
</style></head>
<body><main class="page">
<h1>${escapeHtml(presentation.title)}</h1>
${presentation.presenter ? `<p class="meta">${escapeHtml(presentation.presenter)}</p>` : ''}
${slides}
</main></body></html>`;
}

/** The HTML cover, carrying the same blocks as the DOCX and PDF title pages. */
function renderCover(report: ResolvedReport): string {
  const cover = buildCover(report);
  const theme = getTheme(report.theme);

  const parties = [
    cover.preparedBy ? { label: 'Prepared by', value: cover.preparedBy } : null,
    cover.preparedFor ? { label: 'Prepared for', value: cover.preparedFor } : null,
  ].filter((party): party is { label: string; value: string } => party !== null);

  return `<header class="cover ${theme.cover}">
  <div class="doc-type">${escapeHtml(cover.documentType)}</div>
  <h1>${escapeHtml(cover.title)}</h1>
  ${cover.subtitle ? `<p class="cover-sub">${escapeHtml(cover.subtitle)}</p>` : ''}
  <div class="cover-rule"></div>
  ${cover.project ? `<p class="cover-line">Project &nbsp;<strong>${escapeHtml(cover.project)}</strong></p>` : ''}
  ${
    parties.length > 0
      ? `<div class="parties">${parties
          .map((p) => `<p class="cover-line">${p.label} &nbsp;<strong>${escapeHtml(p.value)}</strong></p>`)
          .join('')}</div>`
      : ''
  }
  <div class="control">
    ${cover.control
      .map(
        (field) =>
          `<div><div class="ctrl-label">${escapeHtml(field.label)}</div>` +
          `<div class="ctrl-value">${escapeHtml(field.value)}</div></div>`,
      )
      .join('')}
  </div>
  <p class="cover-notice">${escapeHtml(cover.notice)}</p>
</header>`;
}

function slugAnchor(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-');
}
