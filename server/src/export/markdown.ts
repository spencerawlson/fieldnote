/** Markdown and self-contained HTML renderers. */

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

// --- Markdown -------------------------------------------------------------

export function renderReportMarkdown(report: ResolvedReport): string {
  const out: string[] = [
    `# ${report.title}`,
    '',
    report.subtitle ? `*${report.subtitle}*` : '',
    '',
    `**Project:** ${report.projectTitle}  `,
    report.author ? `**Author:** ${report.author}  ` : '',
    `**Generated:** ${new Date(report.generatedAt).toISOString().slice(0, 10)}`,
    '',
    '## Contents',
    '',
    ...report.sections.map((s, i) => `${i + 1}. [${s.heading}](#${slugAnchor(s.heading)})`),
    '',
    '---',
    '',
  ];

  for (const section of report.sections) {
    out.push(`## ${section.heading}`, '');
    for (const block of section.blocks) out.push(...markdownBlock(block), '');
  }

  out.push('---', '', `<sub>Generated by Fieldnote. Statements marked as inference or recommendation are AI-generated and not statements of fact.</sub>`);
  return out.filter((line) => line !== undefined).join('\n').replace(/\n{3,}/g, '\n\n');
}

function markdownBlock(block: ReportBlock): string[] {
  switch (block.type) {
    case 'paragraph':
      return [block.text];
    case 'heading':
      return [`${'#'.repeat(block.level)} ${block.text}`];
    case 'bullets':
      return block.items.map((item, i) => (block.ordered ? `${i + 1}. ${item}` : `- ${item}`));
    case 'procedure':
      return block.items.map((item, i) => `${i + 1}. **${item.text}**${item.detail ? `  \n   ${item.detail}` : ''}`);
    case 'code':
      return [`\`\`\`${block.language}`, block.content, '```', block.caption ? `*${block.caption}*` : ''];
    case 'table':
      return [
        block.caption ? `**${block.caption}**` : '',
        `| ${block.headers.join(' | ')} |`,
        `| ${block.headers.map(() => '---').join(' | ')} |`,
        ...block.rows.map((row) => `| ${row.map((cell) => String(cell).replace(/\|/g, '\\|')).join(' | ')} |`),
      ];
    case 'figure':
      return [`**Figure ${block.number ?? '?'}** — ${block.caption}`, '', `> _Image: evidence \`${block.evidenceId}\`_`];
    case 'callout': {
      const prefix = { note: 'Note', warning: 'Caution', inference: 'Inferred', recommendation: 'Recommendation' }[block.variant];
      return [`> **${prefix}:** ${block.text}`];
    }
    case 'diagram':
      return [block.title ? `**${block.title}**` : '', '```text', block.ascii, '```', block.caption ? `*${block.caption}*` : ''];
    case 'reference-list':
      return block.items.map((item, i) => `${i + 1}. ${item.label}${item.url ? ` — <${item.url}>` : ''}${item.detail ? ` — ${item.detail}` : ''}`);
    default:
      return [];
  }
}

export function renderPresentationMarkdown(presentation: ResolvedPresentation): string {
  const out: string[] = [`# ${presentation.title}`, ''];
  if (presentation.subtitle) out.push(`*${presentation.subtitle}*`, '');
  if (presentation.presenter) out.push(`**Presenter:** ${presentation.presenter}`, '');

  for (const slide of presentation.slides) {
    out.push('---', '', `## Slide ${slide.position + 1}: ${slide.title}`, '');
    if (slide.subtitle) out.push(`*${slide.subtitle}*`, '');
    for (const bullet of slide.bullets) out.push(`- ${bullet}`);
    if (slide.body.table) {
      out.push(
        '',
        `| ${slide.body.table.headers.join(' | ')} |`,
        `| ${slide.body.table.headers.map(() => '---').join(' | ')} |`,
        ...slide.body.table.rows.map((r) => `| ${r.join(' | ')} |`),
      );
    }
    if (slide.body.code) out.push('', `\`\`\`${slide.body.code.language}`, slide.body.code.content, '```');
    if (slide.body.diagram) out.push('', '```text', slide.body.diagram.ascii, '```');
    if (slide.body.before || slide.body.after) {
      out.push('');
      if (slide.body.before) out.push(`**${slide.body.before.heading}**`, ...slide.body.before.bullets.map((b) => `- ${b}`));
      if (slide.body.after) out.push(`**${slide.body.after.heading}**`, ...slide.body.after.bullets.map((b) => `- ${b}`));
    }
    for (const figure of slide.figures) out.push('', `_Figure: ${figure.caption}_`);
    if (slide.speakerNotes) out.push('', '**Speaker notes**', '', slide.speakerNotes);
    out.push('');
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

